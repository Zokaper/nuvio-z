//! The installer's QR codes are drawn from `ui/qr.js`, a file generated here, so the screens (and the render
//! harness, which has no Rust behind it) show real codes with no QR library in the page.
//!
//! This test regenerates the file and fails if the committed one differs; run it with `NUVIOZ_WRITE_QR=1` to
//! rewrite it. Every code is also decoded back, so a code that would scan as something else cannot ship.
use qrcode::{Color, EcLevel, QrCode};

/// What each code opens. Keep in step with the steps that show them (`ui/steps.js`).
const CODES: &[(&str, &str)] = &[
    ("localDevVpn", "https://apps.apple.com/app/localdevvpn/id6755608044"),
    // The old assistant's deep link (iosSetup SourceLink.kt): the Camera offers "Open in SideStore", which adds the source.
    ("sideStoreSource", "sidestore://source?url=https%3A%2F%2Fraw.githubusercontent.com%2FZokaper%2Fnuvio-z%2Fmain%2Fdistribution%2Fsidestore%2Fsource.json"),
];

const QUIET: usize = 2;

fn svg(code: &QrCode) -> String {
    let n = code.width();
    let colors = code.to_colors();
    let mut path = String::new();
    for y in 0..n {
        for x in 0..n {
            if colors[y * n + x] == Color::Dark {
                path.push_str(&format!("M{} {}h1v1h-1z", x + QUIET, y + QUIET));
            }
        }
    }
    let size = n + 2 * QUIET;
    format!(r##"<svg viewBox="0 0 {size} {size}" shape-rendering="crispEdges"><rect width="{size}" height="{size}" fill="#fff"/><path d="{path}" fill="#000"/></svg>"##)
}

fn decode(code: &QrCode) -> String {
    // Render at 4 px a module with the quiet zone, then read it back with an independent decoder.
    let (n, scale) = (code.width(), 4);
    let colors = code.to_colors();
    let size = (n + 2 * QUIET + 4) * scale;
    let mut image = rqrr::PreparedImage::prepare_from_greyscale(size, size, |x, y| {
        let (mx, my) = ((x / scale) as isize - (QUIET + 2) as isize, (y / scale) as isize - (QUIET + 2) as isize);
        let dark = mx >= 0 && my >= 0 && (mx as usize) < n && (my as usize) < n && colors[my as usize * n + mx as usize] == Color::Dark;
        if dark { 0 } else { 255 }
    });
    let grids = image.detect_grids();
    assert_eq!(grids.len(), 1, "one code in the image");
    grids[0].decode().expect("decodes").1
}

fn generate() -> String {
    let mut out = String::from("// Generated by core/tests/qr_codes.rs (NUVIOZ_WRITE_QR=1 cargo test -p nuvioz-installer-core --test qr_codes).\n// Do not edit: the test fails if this file and the payloads there disagree.\n\"use strict\";\n\nconst QR = {\n");
    for (name, payload) in CODES {
        let code = QrCode::with_error_correction_level(payload.as_bytes(), EcLevel::M).expect("encodes");
        assert_eq!(&decode(&code), payload, "{name} scans back to its payload");
        out.push_str(&format!("  // {payload}\n  {name}: '{}',\n", svg(&code)));
    }
    out.push_str("};\n");
    out
}

#[test]
fn committed_qr_codes_are_current() {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../ui/qr.js");
    let fresh = generate();
    if std::env::var_os("NUVIOZ_WRITE_QR").is_some() {
        std::fs::write(&path, &fresh).unwrap();
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default().replace("\r\n", "\n");
    assert_eq!(committed, fresh, "ui/qr.js is stale: rerun with NUVIOZ_WRITE_QR=1");
}
